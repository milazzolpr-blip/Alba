const { chromium, devices } = require('playwright')
const out = '/tmp/claude-0/-home-claude/1214e15e-fc34-56db-9f1d-4839bd22a61e/scratchpad/'
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ ...devices['Pixel 7'] })
  const p = await ctx.newPage()
  const errs = []
  p.on('pageerror', (e) => errs.push(String(e))); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
  // Data fissa: sabato 14 novembre 2026, come oggi
  await p.clock.install({ time: new Date('2026-11-14T21:50:00+01:00') })
  await p.goto('http://localhost:4173/')
  await p.waitForTimeout(800)
  await p.screenshot({ path: out + 's1-home.png', fullPage: true })
  await p.getByRole('button', { name: 'Inizia allenamento' }).click()
  await p.clock.runFor(65000)
  const checks = p.locator('.set-check')
  await checks.nth(0).click()
  await p.clock.runFor(42000)
  await p.screenshot({ path: out + 's2-session.png' })
  await p.getByRole('button', { name: 'Metti in pausa' }).click()
  await p.clock.runFor(30000)
  await p.screenshot({ path: out + 's3-paused.png' })
  await p.getByRole('button', { name: 'Riprendi', exact: true }).click()
  await p.clock.runFor(200000)
  await p.getByRole('button', { name: 'Inizia serie' }).click()
  await checks.nth(1).click(); await p.clock.runFor(10000); await p.getByRole('button', { name: 'Salta' }).click()
  // superserie: la serie A non avvia recupero
  await checks.nth(8).click()
  const restAfterA = await p.locator('.rest').count()
  const sum = await p.locator('.session-sum').innerText()
  const clock = await p.locator('.clock').innerText()
  await p.locator('.session-body').evaluate((e) => e.scrollTo(0, e.scrollHeight))
  await p.screenshot({ path: out + 's4-end.png' })
  await p.getByRole('button', { name: 'Termina e salva allenamento' }).click()
  await p.waitForTimeout(300)
  await p.screenshot({ path: out + 's5-log.png', fullPage: true })
  await p.getByRole('button', { name: 'Schede' }).click(); await p.locator('.prog').first().click(); await p.waitForTimeout(200)
  await p.screenshot({ path: out + 's6-program.png', fullPage: true })
  await p.getByRole('button', { name: 'Archivio' }).click(); await p.getByRole('tab', { name: 'Esercizi' }).click()
  await p.getByRole('button', { name: /Panca piana bilanciere/ }).click(); await p.waitForTimeout(200)
  await p.screenshot({ path: out + 's7-exercise.png', fullPage: true })
  await p.getByRole('button', { name: 'Oggi' }).click(); await p.waitForTimeout(200)
  await p.screenshot({ path: out + 's8-home2.png', fullPage: true })
  const overflow = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  console.log(JSON.stringify({ errs, restAfterA, sum, clock, overflow }))
  await b.close()
})()
